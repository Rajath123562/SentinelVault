    # Analyst cannot revoke sessions (403)
    resp_a_revoke = client.post("/api/auth/sessions/revoke", headers={"Authorization": f"Bearer {token_a}"}, json={"token": "t"})
    assert resp_a_revoke.status_code == 403

    # Auditor cannot run queries without execute permission (auditor does not have dataset.query.execute)
    resp_aud_query = client.post(
        "/api/queries/run",
        headers={"Authorization": f"Bearer {token_aud}"},
        json={"dataset_id": "health", "field": "age_group", "operator": "equals", "value": "18-35", "epsilon": 0.5}
    )
    assert resp_aud_query.status_code == 403

    # Steward CAN view security events (200)
    resp_s_events = client.get("/api/security/events", headers={"Authorization": f"Bearer {token_s}"})
    assert resp_s_events.status_code == 200


