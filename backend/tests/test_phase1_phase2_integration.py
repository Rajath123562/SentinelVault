def test_i04_granular_rbac_boundary_enforcement(client: TestClient):
    """I04: Zero-Trust RBAC boundaries strictly enforced between analyst, steward, and auditor."""
    token_a = client.post("/api/auth/login", json={"username": "analyst_user", "password": "AnalystPass2026!"}).json()["token"]
    token_aud = client.post("/api/auth/login", json={"username": "auditor_user", "password": "AuditorPass2026!"}).json()["token"]
    token_s = client.post("/api/auth/login", json={"username": "steward_user", "password": "StewardPass2026!"}).json()["token"]

    # Analyst cannot view security events (403)
    resp_a_events = client.get("/api/security/events", headers={"Authorization": f"Bearer {token_a}"})
