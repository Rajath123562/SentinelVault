def test_i11_privileged_account_mfa_protection(client: TestClient):
    """I11: Data steward account enrolled with MFA cannot log in without valid TOTP code."""
    username = f"steward_mfa_{secrets.token_hex(4)}"
    conn = get_connection()
    with conn:
        h, s = hash_password("StewardMfa2026!")
        conn.execute(
            "INSERT INTO users (username, password_hash, salt, role, failed_attempts, locked_until, created_at, status) VALUES (?, ?, ?, 'data_steward', 0, NULL, ?, 'ACTIVE')",
            (username, h, s, datetime.now(timezone.utc).isoformat())
        )

    # Initial login & MFA enrollment
    init_token = client.post("/api/auth/login", json={"username": username, "password": "StewardMfa2026!"}).json()["token"]
    enroll_data = client.post("/api/auth/mfa/enroll", headers={"Authorization": f"Bearer {init_token}"}).json()
    secret = enroll_data["secret"]

    # Verify code to activate
    current_time_step = int(time.time() // 30)
    valid_code = compute_totp_code(secret, current_time_step)
    client.post("/api/auth/mfa/verify", headers={"Authorization": f"Bearer {init_token}"}, json={"code": valid_code})

    # Login without MFA rejected
    login_no_code = client.post("/api/auth/login", json={"username": username, "password": "StewardMfa2026!"})
    assert login_no_code.status_code == 401
    assert "MFA verification code required" in login_no_code.json()["detail"]

    # Login with valid MFA code succeeds
    fresh_code = compute_totp_code(secret, int(time.time() // 30))
    login_with_code = client.post("/api/auth/login", json={"username": username, "password": "StewardMfa2026!", "mfa_code": fresh_code})
    assert login_with_code.status_code == 200
    assert "token" in login_with_code.json()


